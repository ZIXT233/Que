import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync,writeFileSync,rmSync,readFileSync,existsSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import readline from 'node:readline';
import { createHash } from 'node:crypto';

test('real acpx owner: approval, queued message, controls, reconnect, persistent resume', async () => {
 const root=mkdtempSync(path.join(os.tmpdir(),'flat-acp-test-'));
 writeFileSync(path.join(root,'agents.json'),JSON.stringify({fixture:[process.execPath,path.resolve('tests/acp/agent.mjs')]}));
 let child, serial=0;const pending=new Map();
 const connect=()=>{
   child=spawn(process.execPath,['src-tauri/resources/bin/flat-acp.mjs'],{env:{...process.env,FLAT_ACP_ROOT:root,FLAT_ACP_STORE_DIR:path.join(root,"acpx")},stdio:['pipe','pipe','pipe']});
   child.stderr.on('data',d=>process.stderr.write(d));
   readline.createInterface({input:child.stdout}).on('line',line=>{const v=JSON.parse(line);if(v.rpc){const p=pending.get(v.rpc);pending.delete(v.rpc);v.error?p.reject(Error(v.error)):p.resolve(v.result)}});
 };
 const rpc=body=>new Promise((resolve,reject)=>{const id=String(++serial);pending.set(id,{resolve,reject});child.stdin.write(JSON.stringify({...body,rpc:id})+'\n')});
 const wait=async(predicate)=>{for(let i=0;i<150;i++){const v=await rpc({action:'read',id:'card'});if(predicate(v))return v;await new Promise(r=>setTimeout(r,40))}throw Error('Timeout '+JSON.stringify((await rpc({action:'read',id:'card'})).turns.map(t=>({state:t.state,result:t.result}))))};
 connect();
 try {
   const all=await rpc({action:'history_native',agent:'fixture',cwd:root,allWorkspaces:true});assert.equal(all.sessions.length,2);assert.ok(all.sessions.some(s=>s.cwd==='/tmp/another-workspace'));
   const native=await rpc({action:'history_native',agent:'fixture',cwd:root});assert.equal(native.supported,true);assert.equal(native.sessions[0].title,'First native');
   assert.equal((await rpc({action:'history_native',agent:'fixture',cwd:root,cursor:native.nextCursor})).sessions[0].title,'Second native');
   await rpc({action:'ensure',id:'card',agent:'fixture',cwd:root});
   await rpc({action:'model',id:'card',value:'large'});
   assert.equal((await rpc({action:'send',id:'card',requestId:'one',text:'permission'})).state,'running');
   const waiting=await wait(s=>s.turns[0].blocks.some(b=>b.type==='decision'));
   const decision=waiting.turns[0].blocks.find(b=>b.type==='decision');assert.equal(waiting.state,'attention');
   assert.equal((await rpc({action:'send',id:'card',requestId:'two',text:'second'})).state,'queued');
   await assert.rejects(rpc({action:'close',id:'card'}),/当前操作/);
   assert.equal((await rpc({action:'read',id:'card'})).state,'attention');
   await rpc({action:'model',id:'card',value:'small'});
   await rpc({action:'model',id:'card',value:'large'});
   assert.equal((await rpc({action:'read',id:'card'})).turns[1].state,'queued');
   child.kill();connect();
   const recovered=await rpc({action:'read',id:'card'});assert.equal(recovered.turns[0].blocks.find(b=>b.type==='decision').id,decision.id);
   await rpc({action:'answer',id:'card',decisionId:decision.id,answer:{outcome:'allow_once'}});
   const done=await wait(s=>s.turns.every(t=>t.state==='completed'));
   assert.equal(done.title,'Fixture native title');
   assert.equal(done.turns[0].blocks.filter(b=>b.type==='tool_call').length,1);
   assert.equal(done.turns[0].blocks.find(b=>b.type==='tool_call').title,'查看项目文件');
   assert.match(done.turns[1].blocks.filter(b=>b.type==='text_delta').map(b=>b.text).join(''),/large/);
   await rpc({action:'send',id:'card',requestId:'two',text:'second'});assert.equal((await rpc({action:'read',id:'card'})).turns.length,2);
   await rpc({action:'close',id:'card'});
   await rpc({action:'ensure',id:'card',agent:'fixture',cwd:root});
   assert.equal((await rpc({action:'read',id:'card'})).turns.length,2);
   await rpc({action:'send',id:'card',requestId:'file',text:'file-check',butlerContext:'Butler fixture instructions',attachments:[{mediaType:'text/plain',name:'example.ts',data:'const answer = 42;'}]});
   const fileDone=await wait(s=>s.turns.find(t=>t.id==='file')?.state==='completed');
   const fileOutput=fileDone.turns.find(t=>t.id==='file').blocks.filter(b=>b.type==='text_delta').map(b=>b.text).join('');
   assert.match(fileOutput,/Butler fixture instructions/);assert.match(fileOutput,/example.ts/);assert.match(fileOutput,/const answer = 42/);
   await assert.rejects(rpc({action:'send',id:'card',requestId:'badfile',text:'bad',attachments:[{mediaType:'text/plain',name:'bad.txt',data:'a\0b'}]}),/Invalid text file/);
   await rpc({action:'close',id:'card'});
   assert.equal((await rpc({action:'close',id:'card'})).state,'not_running');
   const history=await rpc({action:'history',cwd:root});assert.equal(history.length,1);assert.equal(history[0].cardId,'card');
   assert.deepEqual(await rpc({action:'history',cwd:path.join(root,'elsewhere')}),[]);
   const rawBindings=readFileSync(path.join(root,'bindings.json'),'utf8');assert.ok(!rawBindings.includes('const answer = 42'));assert.ok(!existsSync(path.join(root,'sessions.json')));
   child.kill();process.kill(Number(readFileSync(path.join(root,'owner.pid'),'utf8')));
   await new Promise(resolve=>setTimeout(resolve,300));
   connect();
   const afterRestart=await rpc({action:'read',id:'card'});
   assert.equal(afterRestart.title,'Fixture native title');
   assert.ok(!afterRestart.turns.map(t=>t.text).join(' ').includes('Butler fixture instructions'));
   assert.ok(afterRestart.turns[0].blocks.find(b=>b.type==='tool_call').content.some(c=>c.type==='diff'));
   assert.match(afterRestart.turns.map(t=>t.text).join(' '),/const answer = 42/);
   assert.match(afterRestart.turns.flatMap(t=>t.blocks).filter(b=>b.type==='text_delta').map(b=>b.text).join(' '),/large/);
   assert.equal((await rpc({action:'attach',id:'second-card',recordId:history[0].recordId,cwd:root})).id,'card');
   await assert.rejects(rpc({action:'attach',id:'bad-card',recordId:history[0].recordId,cwd:path.join(root,'elsewhere')}),/工作区/);
   // Sending to a stopped card reconnects without a separate resume action.
   await rpc({action:'send',id:'card',requestId:'resumed',text:'after owner restart'});
   await wait(s=>s.turns.find(t=>t.id==='resumed')?.state==='completed');
   await rpc({action:'send',id:'card',requestId:'hold',text:'permission'});
   const hold=await wait(s=>s.turns.find(t=>t.id==='hold')?.blocks.some(b=>b.type==='decision'));
   await assert.rejects(rpc({action:'cancel',id:'card',requestId:'hold',queuedOnly:true}),/消息已开始处理/);
   await assert.rejects(rpc({action:'host_access',id:'card',enabled:true}),/请等待/);
   await rpc({action:'send',id:'card',requestId:'withdraw',text:'do not execute'});
   await rpc({action:'cancel',id:'card',requestId:'withdraw',queuedOnly:true});
   assert.equal((await rpc({action:'read',id:'card'})).turns.find(t=>t.id==='withdraw').withdrawn,true);
   const approval=hold.turns.find(t=>t.id==='hold').blocks.find(b=>b.type==='decision');
   await rpc({action:'answer',id:'card',decisionId:approval.id,answer:{outcome:'allow_once'}});
   const cancelled=await wait(s=>s.turns.find(t=>t.id==='withdraw')?.state==='cancelled');
   assert.equal(cancelled.turns.find(t=>t.id==='withdraw').blocks.length,0);

   const checkTerminal=async(id,expected)=>{
     await rpc({action:'send',id:'card',requestId:id,text:'host-terminal-check'});
     const done=await wait(s=>s.turns.find(t=>t.id===id)?.state==='completed');
     assert.match(done.turns.find(t=>t.id===id).blocks.map(b=>b.text||'').join(''),new RegExp(expected));
   };
   assert.equal((await rpc({action:'read',id:'card'})).hostAccess,true);
   await checkTerminal('host-default','host-terminal-ok');
   await rpc({action:'host_access',id:'card',enabled:false});
   await checkTerminal('host-denied','host-terminal-denied');
   await assert.rejects(rpc({action:'host_access',id:'card',enabled:'yes'}),/Invalid/);
   assert.equal((await rpc({action:'host_access',id:'card',enabled:true})).hostAccess,true);
   await checkTerminal('host-allowed','host-terminal-ok');
   assert.equal(JSON.parse(readFileSync(path.join(root,'bindings.json'),'utf8')).card.hostAccess,true);
   assert.equal((await rpc({action:'host_access',id:'card',enabled:false})).hostAccess,false);
   await rpc({action:'close',id:'card'});
   await rpc({action:'ensure',id:'card',agent:'fixture',cwd:root});
   assert.equal((await rpc({action:'read',id:'card'})).hostAccess,false);
   await checkTerminal('host-denied-again','host-terminal-denied');
   await rpc({action:'close',id:'card'});
   await assert.rejects(rpc({action:'attach',id:'locked-card',nativeSessionId:'locked-native',agent:'fixture',cwd:root}),/另一个 Codex 实例/);
   assert.match((await rpc({action:'read',id:'locked-card'})).error,/关闭原来的会话/);
   const adopted=await rpc({action:'attach',id:'native-card',nativeSessionId:'native-one',agent:'fixture',cwd:root});
   assert.equal(adopted.status.backendSessionId,'native-one');
   assert.equal(adopted.turns[0].text,'Earlier user question');
   assert.ok(adopted.turns[0].blocks.some(b=>b.text==='Earlier agent answer'));
   const nativeRecord=JSON.parse(readFileSync(path.join(root,'acpx','sessions',encodeURIComponent(adopted.recordId)+'.json'),'utf8'));
   assert.ok(nativeRecord.messages.length>=2);
   assert.equal((await rpc({action:'attach',id:'duplicate-native',nativeSessionId:'native-one',agent:'fixture',cwd:root})).id,'native-card');
   await rpc({action:'close',id:'native-card'});
   const configFile=path.join(root,'mcp-config.json');
   const senderSession=await rpc({action:'ensure',id:'sender',agent:'fixture',cwd:root,mcpBridge:'/fixture/que-mcp.cjs',env:{FLAT_TEST_MCP_FILE:configFile}});
   const config=JSON.parse(readFileSync(configFile,'utf8'))[0];
   assert.equal(config.name,'flat');assert.equal(config.args[0],'/fixture/que-mcp.cjs');
   assert.equal(config.env.find(e=>e.name==='FLAT_SOURCE_CARD').value,'sender');
   assert.equal(config.env.find(e=>e.name==='FLAT_SOURCE_EPOCH').value,senderSession.connectionId);
   await rpc({action:'ensure',id:'card',agent:'fixture',cwd:root});
   const sender={cardId:'sender',name:'Fixture A',epoch:senderSession.connectionId};
   await rpc({action:'send',id:'card',requestId:'peer',text:'Agent message',sender});
   const peer=await wait(s=>s.turns.find(t=>t.id==='peer')?.state==='completed');
   assert.deepEqual(peer.turns.find(t=>t.id==='peer').sender,sender);
   await rpc({action:'send',id:'card',requestId:'peer',text:'Agent message',sender});
   assert.equal((await rpc({action:'read',id:'card'})).turns.filter(t=>t.id==='peer').length,1);
   await assert.rejects(rpc({action:'send',id:'card',requestId:'peer',text:'Agent message',sender:{...sender,cardId:'other'}}),/conflict/);
   await rpc({action:'send',id:'card',requestId:'notify-hold',text:'watch-hold'});
   await wait(s=>s.turns.find(t=>t.id==='notify-hold')?.state==='running');
   const notification=await rpc({action:'send',id:'card',requestId:'notification',text:'status data',mode:'notification'});
   assert.equal(notification.state,'queued');assert.equal(notification.source,'event');
   await rpc({action:'send',id:'card',requestId:'notification',text:'status data',mode:'notification'});
   await wait(s=>s.turns.find(t=>t.id==='notification')?.state==='completed');
   assert.equal((await rpc({action:'read',id:'card'})).turns.filter(t=>t.id==='notification').length,1);
   await rpc({action:'close',id:'card'});await rpc({action:'close',id:'sender'});
   child.kill();process.kill(Number(readFileSync(path.join(root,'owner.pid'),'utf8')));
   await new Promise(resolve=>setTimeout(resolve,300));connect();
   assert.deepEqual((await rpc({action:'read',id:'card'})).turns.find(t=>t.id==='peer').sender,sender);
   assert.equal((await rpc({action:'read',id:'card'})).turns.find(t=>t.id==='notification').source,'event');

 } finally {
   child.kill();
   // The owner exposes a PID only in its test profile for precise cleanup.
   try {process.kill(Number(readFileSync(path.join(root,'owner.pid'),'utf8')))} catch {}
   for(let i=0;i<240&&existsSync(path.join(root,'owner.pid'));i++) await new Promise(r=>setTimeout(r,50));
   assert.equal(existsSync(path.join(root,'owner.pid')),false,'owner must finish shutdown before cleanup');
   rmSync(root,{recursive:true,force:true});
   try{rmSync(path.join(os.tmpdir(),`flat-${createHash('sha256').update(`${root}:acpx-history-v2`).digest('hex').slice(0,20)}.sock`))}catch{}
 }
});
